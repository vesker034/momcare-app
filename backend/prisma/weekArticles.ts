function emptyToNull(value: string | null | undefined): string | null {
  if (value == null) {
    return null;
  }
  const trimmed = value.trim();
  if (!trimmed || trimmed === '—' || trimmed === '-') {
    return null;
  }
  return trimmed;
}

function categoryLabel(category: ArticleCategory): string {
  switch (category) {
    case ArticleCategory.NUTRITION:
      return 'питание и питьевой режим';
    case ArticleCategory.ACTIVITY:
      return 'движение и отдых';
    case ArticleCategory.CHECKLISTS:
      return 'организацию дел';
    case ArticleCategory.DOCTOR:
      return 'подготовку к разговору с врачом';
    default:
      return 'самочувствие и повседневный ритм';
  }
}

export function buildUniqueWeekArticle(
  week: WeekSeedLike,
  category: ArticleCategory,
): { title: string; summary: string; content: string } {
  const focus = FOCUS_BY_WEEK[week.week] ?? 'спокойные повседневные ориентиры';
  const fruit = emptyToNull(week.fruitComparison);
  const size = emptyToNull(week.babySize);
  const weight = emptyToNull(week.babyWeight);
  const topic = categoryLabel(category);

  const title = `${week.week}-я неделя: ${focus}`;
  const summary = `О ${topic} на ${week.week}-й неделе: ${focus}.`;

  const babySizeLine = fruit
    ? `Сравнение «как ${fruit}» — лишь наглядный ориентир размера.`
    : 'На этом сроке сравнение размера ещё может быть условным.';

  const metricsLine = [
    size ? `Ориентир размера: ${size}.` : null,
    weight ? `Ориентир веса: ${weight}.` : null,
  ]
    .filter(Boolean)
    .join(' ');

  const motherFocus =
    category === ArticleCategory.NUTRITION
      ? `На ${week.week}-й неделе замечайте, как еда и вода влияют на самочувствие: что даёт лёгкость, а что вызывает дискомфорт.`
      : category === ArticleCategory.ACTIVITY
        ? `На ${week.week}-й неделе важнее ощущение после нагрузки: стало ли легче дышать или появилась тянущая усталость.`
        : category === ArticleCategory.CHECKLISTS
          ? `На ${week.week}-й неделе удобно разделить дела на три коротких списка: здоровье, документы и быт.`
          : category === ArticleCategory.DOCTOR
            ? `Перед визитом на ${week.week}-й неделе соберите 3–5 конкретных вопросов и короткие заметки о самочувствии.`
            : `На ${week.week}-й неделе полезно отмечать сон, настроение и моменты усталости или тревоги.`;

  const attentionFocus =
    week.week <= 12
      ? 'Если врач рекомендовал ранние обследования или анализы, уточните подготовку заранее и запишите дату.'
      : week.week <= 27
        ? 'Если назначены УЗИ, скрининг или другие обследования, подготовьте документы и вопросы заранее.'
        : 'На поздних сроках удобно держать под рукой документы, контакты и уточнить у врача, какие признаки требуют связи со специалистом.';

  const content = [
    'Краткое описание',
    `На ${week.week}-й неделе в фокусе: ${focus}.`,
    'Что происходит с малышом',
    `Развитие на ${week.week}-й неделе идёт индивидуально. ${babySizeLine} ${metricsLine}`.trim(),
    'Какие изменения может замечать будущая мама',
    motherFocus,
    'На что можно обратить внимание',
    `${attentionFocus} Решения об обследованиях и лечении обсуждайте с врачом.`,
  ].join('\n\n');

  return { title, summary, content };
}

